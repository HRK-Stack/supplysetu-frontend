// ─── Inline IDB helpers (SW context — cannot import src/lib/idb.ts) ──────────
//
// These mirror the object store layout defined in src/lib/idb.ts exactly.
// If you change the DB name, version, or store names there, update them here too.

const IDB_NAME    = "supplysetu_sync";
const IDB_VERSION = 1;
const STORE_QUEUE     = "sync_queue";
const STORE_CONFLICTS = "sync_conflicts";
const STORE_CACHE_SW  = "cache";

/** Opens the same IndexedDB database as src/lib/idb.ts. */
function openIdb() {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(IDB_NAME, IDB_VERSION);

    req.onupgradeneeded = (event) => {
      const db = event.target.result;
      if (!db.objectStoreNames.contains(STORE_QUEUE)) {
        const qs = db.createObjectStore(STORE_QUEUE, { keyPath: "id" });
        qs.createIndex("timestamp", "timestamp", { unique: false });
      }
      if (!db.objectStoreNames.contains(STORE_CONFLICTS)) {
        const cs = db.createObjectStore(STORE_CONFLICTS, { keyPath: "id" });
        cs.createIndex("conflict_at", "conflict_at", { unique: false });
      }
      if (!db.objectStoreNames.contains(STORE_CACHE_SW)) {
        const ca = db.createObjectStore(STORE_CACHE_SW, { keyPath: "key" });
        ca.createIndex("timestamp", "timestamp", { unique: false });
      }
    };

    req.onsuccess = (e) => resolve(e.target.result);
    req.onerror   = (e) => reject(e.target.error);
  });
}

/** Returns all queued mutations sorted oldest-first. */
async function idbGetAllQueue() {
  const db  = await openIdb();
  const all = await new Promise((resolve, reject) => {
    const tx  = db.transaction(STORE_QUEUE, "readonly");
    const req = tx.objectStore(STORE_QUEUE).getAll();
    req.onsuccess = () => resolve(req.result);
    req.onerror   = () => reject(req.error);
  });
  db.close();
  return all.sort(
    (a, b) => new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime(),
  );
}

/** Removes a mutation from the queue by id. */
async function idbDeleteFromQueue(id) {
  const db = await openIdb();
  await new Promise((resolve, reject) => {
    const tx  = db.transaction(STORE_QUEUE, "readwrite");
    const req = tx.objectStore(STORE_QUEUE).delete(id);
    req.onsuccess = () => resolve();
    req.onerror   = () => reject(req.error);
  });
  db.close();
}

/** Moves a mutation from sync_queue to sync_conflicts. */
async function idbMoveToConflicts(mutation, serverVersion) {
  const db = await openIdb();
  await new Promise((resolve, reject) => {
    const tx        = db.transaction([STORE_QUEUE, STORE_CONFLICTS], "readwrite");
    const conflict  = {
      id: mutation.id,
      mutation,
      conflict_at:    new Date().toISOString(),
      server_version: serverVersion,
    };
    tx.objectStore(STORE_CONFLICTS).put(conflict);
    tx.objectStore(STORE_QUEUE).delete(mutation.id);
    tx.oncomplete = () => resolve();
    tx.onerror    = () => reject(tx.error);
  });
  db.close();
}

/** Increments retry_count on a queued mutation (replace record). */
async function idbUpdateRetryCount(mutation) {
  const db      = await openIdb();
  const updated = { ...mutation, retry_count: (mutation.retry_count || 0) + 1 };
  await new Promise((resolve, reject) => {
    const tx  = db.transaction(STORE_QUEUE, "readwrite");
    const req = tx.objectStore(STORE_QUEUE).put(updated);
    req.onsuccess = () => resolve();
    req.onerror   = () => reject(req.error);
  });
  db.close();
}

/** Writes an API response to the IDB cache store. */
async function idbSetCache(key, data) {
  const db = await openIdb();
  await new Promise((resolve, reject) => {
    const tx  = db.transaction(STORE_CACHE_SW, "readwrite");
    const req = tx.objectStore(STORE_CACHE_SW).put({
      key,
      data,
      timestamp: new Date().toISOString(),
    });
    req.onsuccess = () => resolve();
    req.onerror   = () => reject(req.error);
  });
  db.close();
}

/**
 * Reads an API response from the IDB cache.
 * Returns undefined if not found or older than MAX_CACHE_AGE_MS.
 */
const MAX_CACHE_AGE_MS = 5 * 60 * 1000; // 5 minutes

async function idbGetCache(key) {
  const db = await openIdb();
  const entry = await new Promise((resolve, reject) => {
    const tx  = db.transaction(STORE_CACHE_SW, "readonly");
    const req = tx.objectStore(STORE_CACHE_SW).get(key);
    req.onsuccess = () => resolve(req.result);
    req.onerror   = () => reject(req.error);
  });
  db.close();

  if (!entry) return undefined;
  const ageMs = Date.now() - new Date(entry.timestamp).getTime();
  if (ageMs > MAX_CACHE_AGE_MS) return undefined;
  return entry.data;
}
