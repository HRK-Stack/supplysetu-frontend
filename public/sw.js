// public/sw.js
// SupplySetu — Service Worker
//
// Strategy overview:
//   Static assets (JS, CSS, fonts, images)  → Cache-First
//   API responses (/api/v1/*)               → Network-First with IDB fallback
//   Navigation (HTML pages)                 → Network-First with offline page fallback
//   Background sync tag "supplysetu-sync"   → replay queued IDB mutations
//
// Constraints:
//   - Vanilla JS only — no Workbox runtime, no external imports
//   - Self-contained: all IDB access re-implemented inline
//     (cannot import from src/lib/idb.ts — different JS context)
//
// Cache versioning:
//   Bumping CACHE_VERSION invalidates all old caches on activate.
//   The version string should match the app's package.json version in CI.

"use strict";

// ─── Version ──────────────────────────────────────────────────────────────────

const CACHE_VERSION = "v1";
const STATIC_CACHE  = `supplysetu-static-${CACHE_VERSION}`;
const API_CACHE     = `supplysetu-api-${CACHE_VERSION}`;
const ALL_CACHES    = [STATIC_CACHE, API_CACHE];

// ─── Offline fallback page ────────────────────────────────────────────────────

const OFFLINE_PAGE = "/offline.html";

// Static assets to pre-cache on install (app shell).
// In a real CI pipeline this list is generated by Next.js build output.
const PRECACHE_URLS = [
  "/",
  OFFLINE_PAGE,
];

// ─── Route matchers ───────────────────────────────────────────────────────────

/** Returns true for requests that should use Cache-First strategy. */
function isStaticAsset(request) {
  const url = new URL(request.url);
  return (
    url.pathname.startsWith("/_next/static/") ||
    url.pathname.startsWith("/_next/image") ||
    /\.(js|css|woff2?|ttf|otf|eot|svg|png|jpg|jpeg|gif|webp|ico)$/.test(url.pathname)
  );
}

/** Returns true for API calls that should use Network-First + IDB fallback. */
function isApiRequest(request) {
  const url = new URL(request.url);
  return url.pathname.startsWith("/api/v1/");
}

/** Returns true for same-origin navigation requests (HTML pages). */
function isNavigationRequest(request) {
  return request.mode === "navigate";
}

// ─── Install ──────────────────────────────────────────────────────────────────

self.addEventListener("install", (event) => {
  // Skip waiting — activate immediately without waiting for old SW to be released
  self.skipWaiting();

  event.waitUntil(
    caches.open(STATIC_CACHE).then((cache) => {
      // Pre-cache the app shell. Failures are non-fatal — the SW still installs.
      return cache.addAll(PRECACHE_URLS).catch((err) => {
        console.warn("[SW] Pre-cache partial failure (non-fatal):", err);
      });
    }),
  );
});

// ─── Activate ─────────────────────────────────────────────────────────────────

self.addEventListener("activate", (event) => {
  event.waitUntil(
    Promise.all([
      // Take control of all open clients immediately
      self.clients.claim(),

      // Delete any caches from previous versions
      caches.keys().then((cacheNames) =>
        Promise.all(
          cacheNames
            .filter((name) => !ALL_CACHES.includes(name))
            .map((name) => {
              console.log("[SW] Deleting stale cache:", name);
              return caches.delete(name);
            }),
        ),
      ),
    ]),
  );
});

// ─── Fetch ────────────────────────────────────────────────────────────────────

self.addEventListener("fetch", (event) => {
  const { request } = event;

  // Only handle GET requests in the fetch handler.
  // POST/PATCH/DELETE are handled via Background Sync (sync event).
  if (request.method !== "GET") return;

  if (isStaticAsset(request)) {
    event.respondWith(cacheFirst(request));
    return;
  }

  if (isApiRequest(request)) {
    event.respondWith(networkFirstWithIdbFallback(request));
    return;
  }

  if (isNavigationRequest(request)) {
    event.respondWith(networkFirstWithOfflinePage(request));
    return;
  }

  // Default: network only (e.g. third-party requests)
  // Fall through — browser handles it natively.
});

// ─── Strategies ───────────────────────────────────────────────────────────────

/**
 * Cache-First: serve from cache, fall back to network.
 * On network hit, update the cache in the background.
 */
async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;

  try {
    const networkResponse = await fetch(request);
    if (networkResponse.ok) {
      const cache = await caches.open(STATIC_CACHE);
      cache.put(request, networkResponse.clone());
    }
    return networkResponse;
  } catch {
    // Network failed and nothing in cache — return a generic error response
    return new Response("Static asset unavailable offline", { status: 503 });
  }
}

/**
 * Network-First for API calls with IndexedDB fallback.
 *
 * 1. Try the network
 * 2. On success: write response to IDB cache, return response
 * 3. On network failure: read from IDB cache and return stale data
 * 4. If IDB also empty: return 503
 */
async function networkFirstWithIdbFallback(request) {
  const cacheKey = request.url;

  try {
    const networkResponse = await fetch(request);

    if (networkResponse.ok) {
      // Clone before consuming — Response body can only be read once
      const body = await networkResponse.clone().json().catch(() => null);
      if (body !== null) {
        await idbSetCache(cacheKey, body);
      }
    }

    return networkResponse;
  } catch {
    // Network failed — try IDB cache
    const cached = await idbGetCache(cacheKey);
    if (cached !== undefined) {
      return new Response(JSON.stringify(cached), {
        status: 200,
        headers: {
          "Content-Type": "application/json",
          "X-SW-Cache": "idb-fallback",
        },
      });
    }

    return new Response(
      JSON.stringify({
        success: false,
        data: null,
        error: {
          code: "OFFLINE",
          message: "You are offline and no cached data is available.",
          details: {},
        },
      }),
      {
        status: 503,
        headers: { "Content-Type": "application/json" },
      },
    );
  }
}

/**
 * Network-First for navigation requests.
 * Falls back to the pre-cached offline page if both network and cache fail.
 */
async function networkFirstWithOfflinePage(request) {
  try {
    const networkResponse = await fetch(request);
    return networkResponse;
  } catch {
    const cached = await caches.match(request);
    if (cached) return cached;

    const offlinePage = await caches.match(OFFLINE_PAGE);
    if (offlinePage) return offlinePage;

    return new Response("<h1>You are offline</h1>", {
      status: 503,
      headers: { "Content-Type": "text/html" },
    });
  }
}

// ─── Background Sync ──────────────────────────────────────────────────────────

/**
 * The Background Sync tag used by the app.
 * Must match the tag registered by api.ts when a mutation is enqueued offline:
 *   navigator.serviceWorker.ready.then(reg =>
 *     reg.sync.register("supplysetu-sync")
 *   )
 */
const SYNC_TAG = "supplysetu-sync";

self.addEventListener("sync", (event) => {
  if (event.tag === SYNC_TAG) {
    event.waitUntil(replayQueuedMutations());
  }
});

/**
 * Replays all mutations queued in IDB sync_queue in chronological order.
 *
 * Mirrors the logic in src/lib/idb.ts processQueue() but runs inside the SW
 * context (cannot import from src/lib/idb.ts — different JS context).
 *
 * On success (2xx)  → remove from queue
 * On 409            → move to sync_conflicts, post message to clients
 * On other error    → increment retry_count, leave in queue
 *
 * Throws on fatal DB errors so the browser retries the sync event later.
 */
async function replayQueuedMutations() {
  const mutations = await idbGetAllQueue();

  for (const mutation of mutations) {
    try {
      const response = await fetch(mutation.url, {
        method: mutation.method,
        headers: { "Content-Type": "application/json" },
        body: mutation.payload ? JSON.stringify(mutation.payload) : undefined,
        credentials: "include",
      });

      if (response.ok) {
        await idbDeleteFromQueue(mutation.id);
        postToClients({ type: "SYNC_SUCCESS", mutation });
        continue;
      }

      if (response.status === 409) {
        let serverVersion = null;
        try {
          const body = await response.json();
          serverVersion = body?.error?.details?.current_version ?? null;
        } catch { /* ignored */ }

        await idbMoveToConflicts(mutation, serverVersion);
        postToClients({ type: "SYNC_CONFLICT", mutation, serverVersion });
        continue;
      }

      // Other error — increment retry_count, keep in queue
      await idbUpdateRetryCount(mutation);

    } catch (networkErr) {
      // Network failure — leave in queue; throw so the browser schedules retry
      console.warn("[SW] Sync network error for mutation", mutation.id, networkErr);
      throw networkErr;
    }
  }

  postToClients({ type: "SYNC_COMPLETE" });
}

/**
 * Posts a message to all controlled clients (browser tabs).
 * Used to notify the app of sync events so the UI can update.
 */
async function postToClients(message) {
  const clients = await self.clients.matchAll({ type: "window" });
  for (const client of clients) {
    client.postMessage(message);
  }
}

